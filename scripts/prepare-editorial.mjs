import { readdirSync, readFileSync, writeFileSync } from "node:fs";
const preview = process.argv.includes("--preview");
if (preview && process.env.NODE_ENV === "production")
  throw new Error("Editorial preview cannot run in production");
const posts = readdirSync("docs/editorial")
  .filter((f) => f.endsWith(".json"))
  .map((f) => JSON.parse(readFileSync(`docs/editorial/${f}`, "utf8")));
const approved = posts.filter(
  (p) =>
    p.reviewStatus === "approved" && p.reviewer.trim() && /^\d{4}-\d{2}-\d{2}$/.test(p.reviewedAt),
);
const visible = preview ? posts : approved;
writeFileSync(
  "src/components/site/review-guides.generated.ts",
  `// Generated by prepare-editorial.mjs; pending content is excluded from production.\nimport type { Guide } from './guide-data';\nexport const REVIEW_GUIDES: Record<string, Guide> = ${JSON.stringify(Object.fromEntries(visible.map((p) => [p.slug, p])), null, 2)};\n`,
);
let sitemap = readFileSync("public/sitemap.xml", "utf8").replace(
  /\s*<!-- approved-editorial-start -->[\s\S]*?<!-- approved-editorial-end -->/,
  "",
);
sitemap = sitemap.replace(
  "</urlset>",
  `<!-- approved-editorial-start -->\n${approved.map((p) => `<url><loc>https://upliftmedicalms.com/resources/${p.slug}</loc><lastmod>${p.reviewedAt}</lastmod></url>`).join("\n")}\n<!-- approved-editorial-end -->\n</urlset>`,
);
writeFileSync("public/sitemap.xml", sitemap);
console.log(
  `${visible.length} editorial posts included; ${approved.length} approved for production.`,
);
